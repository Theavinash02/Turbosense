import json
from pathlib import Path

import numpy as np


def _lstm_summary(result: dict) -> dict:
    runs = result["lstm"]
    keys = ("val_rmse", "rmse_capped", "rmse_true", "nasa_per_engine")
    return {**{k: float(np.mean([r[k] for r in runs])) for k in keys},
            "rmse_capped_std": float(np.std([r["rmse_capped"] for r in runs], ddof=1)) if len(runs) > 1 else 0.0,
            "seeds": len(runs)}


def build_report(cfg: dict) -> str:
    """Write reports/results.md from the JSON files the other commands produced, and return its text."""
    reports: Path = cfg["paths"]["reports"]
    results = {p.stem.removeprefix("train_"): json.loads(p.read_text()) for p in sorted(reports.glob("train_*.json"))}
    lines = ["# Results", "",
             "Generated by `rul report` from the JSON files in this folder. Errors are in flight cycles.", ""]

    cond = {k: v for k, v in results.items() if v["scaling"] == "condition"}
    if cond:
        lines += ["## Within each subset (per-condition scaling)", "",
                  "| Subset | Conditions | Test engines | LightGBM RMSE | LSTM RMSE | LSTM RMSE, true RUL "
                  "| LightGBM NASA/engine | LSTM NASA/engine |",
                  "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        for r in cond.values():
            s, g = _lstm_summary(r), r["lightgbm"]
            lines.append(f"| {r['subset']} | {r['conditions']} | {r['test_engines']} | {g['rmse_capped']:.2f} | "
                         f"{s['rmse_capped']:.2f} ± {s['rmse_capped_std']:.2f} | {s['rmse_true']:.2f} | "
                         f"{g['nasa_per_engine']:.2f} | {s['nasa_per_engine']:.2f} |")
        n = next(iter(cond.values()))
        lines += ["", f"RMSE is against the true RUL capped at {cfg['labels']['rul_cap']} unless marked. "
                      f"LSTM figures are the mean over {_lstm_summary(n)['seeds']} seeds, ± one standard deviation.",
                  ""]

    glob = {v["subset"]: v for v in results.values() if v["scaling"] == "global"}
    both = [s for s in glob if f"{s}_condition" in results]
    if both:
        lines += ["## Global against per-condition scaling", "",
                  "| Subset | LightGBM, global | LightGBM, per condition | LSTM, global | LSTM, per condition |",
                  "| --- | --- | --- | --- | --- |"]
        for s in both:
            c, g = results[f"{s}_condition"], glob[s]
            sc, sg = _lstm_summary(c), _lstm_summary(g)
            lines.append(f"| {s} | {g['lightgbm']['rmse_capped']:.2f} | {c['lightgbm']['rmse_capped']:.2f} | "
                         f"{sg['rmse_capped']:.2f} ± {sg['rmse_capped_std']:.2f} | "
                         f"{sc['rmse_capped']:.2f} ± {sc['rmse_capped_std']:.2f} |")
        lines.append("")

    transfer = reports / "transfer.json"
    if transfer.exists():
        t = json.loads(transfer.read_text())
        subs = t["subsets"]
        lines += ["## Train on one subset, test on another", "",
                  "Rows are the training subset, columns the test subset. LSTM test RMSE (capped), mean over seeds, "
                  "no retraining; target sensors are scaled with the source subset's statistics.", "",
                  "| Trained on | " + " | ".join(subs) + " |", "| --- |" + " --- |" * len(subs)]
        for src in subs:
            lines.append(f"| {src} | " + " | ".join(f"{t['rmse_capped'][src][tgt]:.1f}" for tgt in subs) + " |")
        lines.append("")

    anomalies = [json.loads(p.read_text()) for p in sorted(reports.glob("anomaly_*.json"))]
    if anomalies:
        s0 = anomalies[0]["settings"]
        ks = s0["near_failure_rul"]
        lines += ["## Health monitor", "",
                  f"Unsupervised distance from each engine's own baseline (its first {s0['baseline_cycles']} cycles). "
                  f"An alarm needs {s0['persist']} cycles in a row above the threshold. Lead time and early alarms "
                  "are measured on held-out validation engines that run to failure; AUROC is measured on the test "
                  "engines at their last observed cycle. An early alarm is one that fires with "
                  f"{cfg['labels']['rul_cap']} or more cycles left.", "",
                  "| Subset | Reference | Engines alarmed before failure | Median lead (cycles) | 10th pct lead "
                  "| Early alarms | " + " | ".join(f"AUROC, RUL ≤ {k}" for k in ks) + " |",
                  "| --- | --- | --- | --- | --- | --- |" + " --- |" * len(ks)]
        for a in anomalies:
            for label, key in (("own baseline", "own_baseline"), ("fleet mean", "fleet_reference")):
                v, t = a[key]["validation"], a[key]["test_auroc"]
                lead = "n/a" if v["median_lead_cycles"] is None else f"{v['median_lead_cycles']:.1f}"
                p10 = "n/a" if v["lead_p10_cycles"] is None else f"{v['lead_p10_cycles']:.0f}"
                lines.append(f"| {a['subset']} | {label} | {v['detected_share']:.0%} | {lead} | {p10} | "
                             f"{v['early_alarm_share']:.0%} | "
                             + " | ".join(f"{t[f'rul_le_{k}']:.3f}" for k in ks) + " |")
        lines.append("")

    text = "\n".join(lines)
    (reports / "results.md").write_text(text)
    return text
